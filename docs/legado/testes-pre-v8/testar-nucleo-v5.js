'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const mem=new Map();
const store={getItem:k=>mem.get(k)||null,setItem:(k,v)=>mem.set(k,String(v)),removeItem:k=>mem.delete(k)};
const ctx={window:{},localStorage:store,Date,Math};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname+'/core/demo-store.js','utf8'),ctx,{filename:'demo-store.js'});
const api=ctx.window.RTDemoStore;
let d=api.load();assert.equal(d.version,7);assert.equal(d.clients.length,3);assert.equal(d.programs.length,3);
assert.equal(api.clientView(d,'does-not-exist'),null);
assert.equal(api.clientView(d,'c1').sessions.length,1);
assert.equal(api.clientView(d,'c2').sessions.some(s=>s.id==='s4'),false,'Private sessions must not be passed to client');
assert.ok(!Object.hasOwn(api.clientView(d,'c1').sessions[0],'summary'),'Internal session summaries must not be passed to client');
d.reflections.push({id:'r-test',clientId:'c1',title:'PRIVADA',text:'private-simulated',visibility:'privado',created:'2026-10-20'});
d.reflections.push({id:'r-test2',clientId:'c1',title:'COMPARTILHADA',text:'shared-simulated',visibility:'compartilhado',created:'2026-10-20'});
assert.equal(api.publicReflections(d,'c1').length,1);
assert.equal(api.publicReflections(d,'c2').length,0);
assert.equal(api.clientView(d,'c2').reflections.length,0);
d.actions.find(x=>x.id==='a1').visibility='privado';assert.equal(api.clientView(d,'c1').actions.some(x=>x.id==='a1'),false,'Internal activity must not render for client');d.actions.find(x=>x.id==='a1').visibility='compartilhado';
d.sessions.find(x=>x.id==='s1').clientTopic='Encontro compartilhado';assert.equal(api.clientView(d,'c1').sessions[0].focus,'Encontro compartilhado','Client should see public title, not internal focus');
assert.equal(api.clientView(d,'c1').reflections.length,2);
d.actions.find(x=>x.id==='a1').status='concluido';
api.save(d);assert.equal(api.load().actions.find(x=>x.id==='a1').status,'concluido');
assert.equal(api.load().reflections.length,2);
api.log(d,'cliente','test-action','a1');api.save(d);assert.equal(api.load().audit.at(-1).actor,'cliente');
api.reset();assert.equal(api.load().reflections.length,0);assert.equal(api.load().actions.find(x=>x.id==='a1').status,'pendente');
console.log('QA núcleo V5: persistência demo, isolamento visual por cliente, compartilhamento, resumo restrito, log e reset OK.');
