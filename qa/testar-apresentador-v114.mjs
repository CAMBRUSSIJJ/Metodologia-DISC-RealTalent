#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const viewer=read('apresentacoes/visualizador.js');
const html=read('apresentacoes/visualizador.html');
const css=read('apresentacoes/visualizador.css');
const launcher=read('abrir-linux.sh');
const installer=read('scripts/ensure-pdfjs-v114.py');
new vm.Script(viewer);
assert.match(viewer,/pdf\.getPage\(state\.page\)/);
assert.match(viewer,/pdf\.numPages/);
assert.match(viewer,/renderTask\.promise/);
assert.match(viewer,/await import\(localMain\.href\)/);
assert.match(viewer,/pdf\.worker\.min\.mjs/);
assert.match(viewer,/state\.inkPages=new Map/);
assert.match(viewer,/function thumbnailPdf\(/);
assert.match(viewer,/function exportInk\(/);
assert.match(viewer,/function undo\(/);
assert.match(viewer,/function redo\(/);
assert.match(viewer,/function measureScale\(/);
assert.match(viewer,/function resizeInk\(/);
assert.match(html,/id="thumbnail-list"/);
assert.match(html,/id="fit-page"/);
assert.match(html,/id="fit-width"/);
assert.match(html,/id="undo-ink"/);
assert.match(html,/id="redo-ink"/);
assert.match(html,/id="export-ink"/);
assert.match(css,/\.page-surface\{/);
assert.match(css,/\.thumb-item\{/);
assert.match(launcher,/python3 scripts\/ensure-pdfjs-v114\.py/);
assert.match(installer,/VERSION="4\.10\.38"/);
assert.doesNotMatch(viewer,/\.innerHTML\s*=/);
console.log('RealTalent V11.4: estrutura, sintaxe, renderização e controles verificados.');
