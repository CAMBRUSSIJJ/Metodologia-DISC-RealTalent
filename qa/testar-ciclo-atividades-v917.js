'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const data=new Map(),localStorage={getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,String(v)),removeItem:k=>data.delete(k),key:i=>[...data.keys()][i]||null,get length(){return data.size}};
const ctx={window:{},localStorage,Date,console};vm.runInNewContext(read('core/demo-store.js'),ctx);
new Function(read('profissional/app.js'));new Function(read('cliente/app.js'));
const S=ctx.window.RTDemoStore,d=S.seed();
const old=S.seed();delete old.instruments[0].goalId;
assert.equal(S.upgrade(old).instruments[0].goalId,'goal-p1','Legado mantém processo');
assert.equal(S.assignGuidedActivity(d,{programId:'p1',goalId:'goal-p2',title:'Exercício cruzado'}),null);
assert.equal(S.assignGuidedActivity(d,{programId:'p1',goalId:'goal-p1',title:'x'}),null);
const item=S.assignGuidedActivity(d,{programId:'p1',goalId:'goal-p1',title:'Reflexão fictícia de comunicação',instructions:'Caso inteiramente imaginário'});
assert.ok(item&&item.visibility==='privado'&&item.goalId==='goal-p1');
assert.equal(S.clientView(d,'c1').instruments.some(i=>i.id===item.id),false,'Rascunho oculto');
assert.equal(S.clientView(d,'c2').instruments.some(i=>i.id===item.id),false,'Clientes isolados');
item.visibility='compartilhado';
assert.equal(S.submitInstrument(d,'c2',item.id,['um','dois','três']),false);
assert.equal(S.submitInstrument(d,'c1',item.id,['situação fictícia','reação fictícia','ação fictícia']),true);
assert.equal(S.submitInstrument(d,'c1',item.id,['segunda','resposta','inválida']),false);
assert.equal(S.reviewGuidedActivity(d,item.id,'Devolutiva privada fictícia','privado'),true);
let view=S.clientView(d,'c1').instruments.find(i=>i.id===item.id);
assert.equal(view.feedback,'','Não vazar devolutiva privada');
assert.equal(view.feedbackVisibility,undefined);
assert.equal(view.status,'devolvido');
assert.equal(S.reviewGuidedActivity(d,item.id,'Orientação compartilhável fictícia','compartilhado'),true);
view=S.clientView(d,'c1').instruments.find(i=>i.id===item.id);
assert.equal(view.feedback,'Orientação compartilhável fictícia');
assert.equal(S.reviewGuidedActivity(d,item.id,'','compartilhado'),true);
assert.equal(S.clientView(d,'c1').instruments.find(i=>i.id===item.id).feedback,'');
d.programs.find(p=>p.id==='p1').status='finalizado';
assert.equal(S.assignGuidedActivity(d,{programId:'p1',goalId:'goal-p1',title:'Atividade após encerramento'}),null);
console.log('V9.17 QA estrutural OK: migração, privacidade, vínculos, resposta única, revisão e compartilhamento.');
