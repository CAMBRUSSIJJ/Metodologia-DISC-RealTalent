from pathlib import Path
from playwright.sync_api import sync_playwright
import re
root=Path(__file__).resolve().parents[1]
import os, tempfile
artifacts=Path(os.environ.get('REALTALENT_QA_OUTPUT',str(Path(tempfile.gettempdir())/'realtalent-v97-qa')))
artifacts.mkdir(parents=True,exist_ok=True)
html=(root/'profissional/index.html').read_text()
html=re.sub(r'<script\b[^>]*\bsrc=[^>]+</script>','',html,flags=re.I)
html=re.sub(r'<link\b[^>]*\brel="stylesheet"[^>]*>','',html,flags=re.I)
css='\n'.join((root/f).read_text() for f in ['profissional/app.css','assets/rt-design-system.css','assets/rt-v7-workspace.css','assets/rt-v8-integration.css','assets/rt-v81-disc.css','assets/rt-v9-professional.css','assets/rt-v92-clients.css','assets/rt-v93-workspace.css'])
css=re.sub(r'@import\s+url\([^)]*\);','',css)
html=html.replace('</head>','<style>'+css+'</style></head>')
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-gpu'])
 page=browser.new_page(viewport={'width':1440,'height':900})
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(html)
 page.evaluate('''() => {const m=new Map();Object.defineProperty(window,'localStorage',{value:{getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,String(v)),removeItem:k=>m.delete(k)}})}''')
 for f in ['core/disc-questions.js','core/demo-store.js','profissional/app.js']:
  page.add_script_tag(content=(root/f).read_text())
 def go(h):
  page.evaluate('(v)=>location.hash=v',h);page.wait_for_timeout(60)
 def must(x,m):
  if not x: raise AssertionError(m)
 # Legacy navigation preserved.
 labels=page.locator('.sidenav [data-page]')
 must(labels.count()==10,'dez itens na sidebar')
 go('#clientes')
 must(page.locator('[data-v92-client-row]').count()==3,'3 clientes iniciais')
 must(page.locator('#rt-v92-client-sort').count()==1,'ordenacao')
 must(page.get_by_role('link',name='Ativos').count()==1,'filtro ativo')
 page.locator('#client-search').fill('demonstrativo 02')
 must(page.locator('[data-v92-client-row]:not([hidden])').count()==1,'busca efetiva')
 page.locator('#client-search').fill('')
 page.locator('#rt-v92-client-sort').select_option('pendencias')
 page.wait_for_timeout(70)
 must('sort=pendencias' in page.evaluate('location.hash'),'ordenacao em hash')
 # Edit client, pause, no duplication, preserve programs.
 first=page.locator('[data-v92-client-row="c2"]')
 firstid=first.get_attribute('data-v92-client-row')
 page.locator(f'[data-v92-client-row="{firstid}"] [data-act="edit-client"]').click()
 must(page.locator('#modal').evaluate('(d)=>d.open'),'modal abrir')
 page.locator('#f-name').fill('Cliente Exemplo Editado')
 page.locator('#f-status').select_option('pausado')
 page.locator('#modal-save').click()
 page.wait_for_timeout(60)
 state=page.evaluate('''id=>({client:db.clients.find(c=>c.id===id),programs:db.programs.filter(p=>p.clientId===id).length,clients:db.clients.length})''',firstid)
 must(state['client']['name']=='Cliente Exemplo Editado','edicao persistida')
 must(state['client']['status']=='pausado','pausado')
 must(state['programs']>=1,'preservar processos')
 must(state['clients']==3,'nao duplicar clientes')
 go('#clientes?filter=pausado')
 must(page.locator('[data-v92-client-row]').count()==1,'filtro pausados')
 go('#clientes?filter=ativo')
 must(page.locator('[data-v92-client-row]').count()==2,'filtro ativos')
 go('#clientes?filter=todos')
 must(page.locator('[data-v92-client-row]').count()==3,'todos inclui pausados')
 # Profile and timeline: filter + process + in-context actions.
 go('#cliente=c1&tab=geral&program=p1')
 must(page.locator('.rt-v92-profile-head h1').inner_text()=='Cliente demonstrativo 01','profile nome')
 must(page.get_by_text('Histórico do acompanhamento').count()==1,'timeline')
 must(page.locator('.rt-v92-timeline-list li').count()>=3,'eventos existentes')
 must(page.locator('.rt-v92-next-action').count()==1,'proxima acao')
 page.locator('.rt-v92-timeline-filters').get_by_role('link',name='Sessões').click()
 page.wait_for_timeout(70)
 must('events=sessao' in page.evaluate('location.hash'),'filtro timeline tipo')
 must(page.locator('.rt-v92-timeline-list li').filter(has_text='Sessão agendada').count()==0,'sessao futura nao e evento ocorrido')
 page.locator('#rt-v92-period').select_option('todos')
 page.wait_for_timeout(70)
 must('period=todos' in page.evaluate('location.hash'),'periodo timeline')
 page.locator('.rt-v93-action-menu summary').click()
 page.locator('.rt-v93-menu-options [data-act="edit-client"]').click()
 must(page.locator('#modal').evaluate('(d)=>d.open'),'editar no workspace')
 page.locator('#modal-cancel').click()
 page.get_by_role('button',name='Agendar sessão').click()
 must(page.locator('#modal').evaluate('(d)=>d.open'),'agendar no contexto')
 page.locator('#modal-cancel').click()
 # Create with minimal data then new process separately.
 go('#clientes')
 page.get_by_role('button',name='+ Novo cliente').click()
 page.locator('#f-name').fill('Cliente fictício novo')
 page.locator('#modal-save').click()
 page.wait_for_timeout(90)
 must(page.locator('.rt-v92-profile-head h1').inner_text()=='Cliente fictício novo','cadastro progressivo')
 must(page.get_by_text('Nenhum processo vinculado').count()==1,'sem processo é permitido')
 page.get_by_role('button',name='Criar processo',exact=True).click()
 page.locator('#f-goal').fill('Explorar estratégias de comunicação')
 page.locator('#modal-save').click()
 page.wait_for_timeout(90)
 must(page.locator('.rt-v92-timeline-list li').count()==1,'evento de processo novo')
 # Mobile nav / tabs.
 page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(80)
 page.locator('#menu-btn').click()
 must('open' in page.locator('#side').get_attribute('class'),'sidebar mobile')
 page.locator('#side [data-page="clientes"]').click()
 page.wait_for_timeout(100)
 must('open' not in page.locator('#side').get_attribute('class'),'menu fecha')
 must(page.locator('.rt-v92-client-tools').count()==1,'lista responsiva')
 # desktop screenshot
 page.set_viewport_size({'width':1440,'height':900});go('#clientes');page.screenshot(path=str(artifacts/'v92-lista.png'),full_page=True)
 go('#cliente=c1&tab=geral&program=p1');page.screenshot(path=str(artifacts/'v92-workspace.png'),full_page=True)
 must(not errors,'Erros JS '+str(errors))
 print('V9.2: clientes list/filter/sort/search/edit/status/new/process/workspace/timeline/responsive OK. JS errors:',errors)
 browser.close()
